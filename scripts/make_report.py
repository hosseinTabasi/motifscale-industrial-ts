"""Render reports/RESULTS.md from experiments/results/*.csv (no hand-typed numbers)."""
import os, json
import pandas as pd
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
R = os.path.join(ROOT, "experiments", "results")


def md(df, nd=4):
    df = df.copy()
    for c in df.columns:
        if df[c].dtype.kind == "f":
            df[c] = df[c].map(lambda v: "" if pd.isna(v) else f"{v:.{nd}f}")
    return df.to_markdown(index=False)


out = ["# MotifScale results (generated by scripts/make_report.py)\n"]
e1 = pd.read_csv(f"{R}/e1_scaling.csv")
p = e1.pivot_table(index="n", columns=["method", "dims"], values="seconds"); p.columns = [f"{a} [{b}-d]" for a, b in p.columns]
out += ["## E1 Runtime vs series length (seconds, CPU)\n", md(p.reset_index(), 3), "\n"]
out += ["## E2 Representativeness vs dictionary size / compute (SKAB anomaly-free, 8 sensors)\n", md(pd.read_csv(f"{R}/e2_pareto_summary.csv")), "\n"]
out += ["## E3 Cross-regime coverage (rows: dictionary source, cols: evaluated group; mean of 3 seeds)\n", md(pd.read_csv(f"{R}/e3_cross_coverage_matrix.csv"), 3), "\n"]
s = pd.read_csv(f"{R}/e3_seed_stability.csv").groupby("group")[["mean_motif_match_rms", "frac_matched"]].mean().reset_index()
out += ["### E3 Seed stability (mean over seed pairs)\n", md(s, 3), "\n"]
t = pd.read_csv(f"{R}/e3_tep_coverage.csv")
out += [f"### E3 TEP: dictionary from d00 normal run covers {t.coverage_normal_prefix.mean():.3f} of normal test prefixes vs {t.coverage_fault.mean():.3f} of faulty segments (mean of 21 runs)\n"]
e4 = pd.read_csv(f"{R}/e4_detection_summary.csv")
cols = ["dataset", "method", "auc_pr_mean", "auc_pr_std", "auc_roc_mean", "f1_best_mean", "f1_best_pa_mean", "f1_ref_thr_mean", "f1_ref_thr_pa_mean", "score_seconds_mean"]
out += ["## E4 Downstream anomaly detection (pooled points; F1 without and with point-adjust)\n", md(e4[cols]), "\n"]
out += ["## E5 Sensitivity to the single knob `budget` (SKAB, 3 seeds)\n", md(pd.read_csv(f"{R}/e5_knob_summary.csv")[["budget", "k_mean", "fit_seconds_mean", "pool_coverage_mean", "auc_pr_mean", "auc_pr_std", "auc_roc_mean", "f1_best_mean", "f1_best_pa_mean"]]), "\n"]
open(os.path.join(ROOT, "reports", "RESULTS.md"), "w").write("\n".join(out))
print("\n".join(out))
